/**
 * @name generateInterviewReportController
 * @description Generates the match report and ATS optimization based on resume (PDF or text), self description, and job description
 * @access private
 */
const generateInterviewReportController = asyncHandler(async (req, res) => {
    let resumeText = "";

    if (req.file) {
        try {
            const parsed = await (new PDFParse(new Uint8Array(req.file.buffer))).getText();
            resumeText = parsed?.text || "";
        } catch (pdfErr) {
            console.error("PDF Parsing error:", pdfErr);
            throw new ApiError(400, "Failed to parse PDF resume. Please ensure it is a valid PDF document.");
        }
    } else if (req.body.resumeText) {
        resumeText = req.body.resumeText;
    }

    const { selfDescription = "", jobDescription } = req.body;

    if (!jobDescription || !jobDescription.trim()) {
        throw new ApiError(400, "Job description is required");
    }

    if (!resumeText.trim() && !selfDescription.trim()) {
        throw new ApiError(400, "Please provide either a resume (PDF/text) or a detailed self description");
    }

    const interviewReportByAi = await generateInterviewReport({
        resume: resumeText,
        selfDescription,
        jobDescription
    });

    const interviewReport = await InterviewReport.create({
        user: req.user.id,
        resume: resumeText,
        selfDescription,
        jobDescription,
        ...interviewReportByAi
    });

    return res.status(201).json(new ApiResponse(
        201,
        interviewReport,
        "Interview Report and ATS suggestions generated successfully"
    ));
});

