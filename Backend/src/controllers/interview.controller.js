/**
 * @name startMockInterviewController
 * @description Initializes an AI Mock Interview session with technical, resume-based, and behavioral questions
 * @access private
 */
const startMockInterviewController = asyncHandler(async (req, res) => {
    const { reportId, jobDescription: reqJd, resume: reqResume, selfDescription: reqSelfDesc, roleTitle: reqTitle } = req.body;

    let resume = reqResume || "";
    let jobDescription = reqJd || "";
    let selfDescription = reqSelfDesc || "";
    let roleTitle = reqTitle || "";

    // If reportId is provided, pull from existing report
    if (reportId) {
        const report = await InterviewReport.findOne({ _id: reportId, user: req.user.id });
        if (report) {
            resume = report.resume || resume;
            jobDescription = report.jobDescription || jobDescription;
            selfDescription = report.selfDescription || selfDescription;
            roleTitle = report.roleTitle || roleTitle;
        }
    }

    if (!jobDescription && !resume && !selfDescription) {
        throw new ApiError(400, "Please provide job description and resume or select an existing report");
    }

    const { roleTitle: generatedTitle, questions } = await generateMockInterviewQuestions({
        resume,
        jobDescription,
        selfDescription,
        roleTitle
    });

    const finalRoleTitle = roleTitle || generatedTitle || "Candidate Role";

    const session = await InterviewSession.create({
        user: req.user.id,
        reportId: reportId || null,
        roleTitle: finalRoleTitle,
        jobDescription,
        resume,
        status: 'in-progress',
        questions: questions.map(q => ({
            id: q.id,
            type: q.type,
            question: q.question,
            context: q.context,
            expectedKeyPoints: q.expectedKeyPoints,
            userAnswer: "",
            score: null,
            feedback: "",
            idealAnswer: ""
        }))
    });

    return res.status(201).json(new ApiResponse(
        201,
        session,
        "Mock interview session started successfully"
    ));
});

/**
 * @name saveMockInterviewProgressController
 * @description Autosaves answers as the candidate moves through the interview
 * @access private
 */
const saveMockInterviewProgressController = asyncHandler(async (req, res) => {
    const { sessionId } = req.params;
    const { answers } = req.body; // array of { id, userAnswer }

    const session = await InterviewSession.findOne({ _id: sessionId, user: req.user.id });
    if (!session) {
        throw new ApiError(404, "Interview session not found");
    }

    if (Array.isArray(answers)) {
        answers.forEach(ans => {
            const q = session.questions.find(item => item.id === ans.id);
            if (q) {
                q.userAnswer = ans.userAnswer;
            }
        });
    }

    await session.save();

    return res.status(200).json(new ApiResponse(
        200,
        session,
        "Interview progress saved"
    ));
});

/**
 * @name evaluateMockInterviewController
 * @description Evaluates all answers, scores performance, provides feedback, and completes interview
 * @access private
 */
const evaluateMockInterviewController = asyncHandler(async (req, res) => {
    const { sessionId } = req.params;
    const { answers } = req.body;

    const session = await InterviewSession.findOne({ _id: sessionId, user: req.user.id });
    if (!session) {
        throw new ApiError(404, "Interview session not found");
    }

    // Update with final answers if provided
    if (Array.isArray(answers)) {
        answers.forEach(ans => {
            const q = session.questions.find(item => item.id === ans.id);
            if (q) {
                q.userAnswer = ans.userAnswer;
            }
        });
    }

    // Call AI to evaluate performance
    const candidateAnswers = session.questions.map(q => ({
        id: q.id,
        userAnswer: q.userAnswer || ""
    }));

    const evaluation = await evaluateInterviewPerformance({
        questions: session.questions,
        candidateAnswers,
        resume: session.resume,
        jobDescription: session.jobDescription,
        roleTitle: session.roleTitle
    });

    // Merge evaluation back into questions
    if (evaluation.evaluatedQuestions) {
        evaluation.evaluatedQuestions.forEach(evalQ => {
            const q = session.questions.find(item => item.id === evalQ.id);
            if (q) {
                q.score = evalQ.score;
                q.feedback = evalQ.feedback;
                q.idealAnswer = evalQ.idealAnswer;
            }
        });
    }

    session.overallEvaluation = {
        overallScore: evaluation.overallScore,
        technicalScore: evaluation.technicalScore,
        communicationScore: evaluation.communicationScore,
        behavioralScore: evaluation.behavioralScore,
        verdict: evaluation.verdict,
        strengths: evaluation.strengths,
        improvements: evaluation.improvements,
        summary: evaluation.summary
    };

    session.status = 'completed';
    await session.save();

    return res.status(200).json(new ApiResponse(
        200,
        session,
        "Interview evaluated and scored successfully"
    ));
});

